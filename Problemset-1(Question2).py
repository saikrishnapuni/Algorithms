# Given:

# $$ F(0)=0,\quad F(1)=1,\quad F(2)=2 $$

# and

# $$ F(n)=(2F(n-1)-3F(n-3))\bmod m $$

# where \(n<10^{105}\) and \(m<10^5\).
def mul(X,Y,m):
    Z = [
        [
            (X[0][0]*Y[0][0] + X[0][1]*Y[1][0] + X[0][2]*Y[2][0]) % m,
            (X[0][0]*Y[0][1] + X[0][1]*Y[1][1] + X[0][2]*Y[2][1]) % m,
            (X[0][0]*Y[0][2] + X[0][1]*Y[1][2] + X[0][2]*Y[2][2]) % m
        ],
        [
            (X[1][0]*Y[0][0] + X[1][1]*Y[1][0] + X[1][2]*Y[2][0]) % m,
            (X[1][0]*Y[0][1] + X[1][1]*Y[1][1] + X[1][2]*Y[2][1]) % m,
            (X[1][0]*Y[0][2] + X[1][1]*Y[1][2] + X[1][2]*Y[2][2]) % m
        ],
        [
            (X[2][0]*Y[0][0] + X[2][1]*Y[1][0] + X[2][2]*Y[2][0]) % m,
            (X[2][0]*Y[0][1] + X[2][1]*Y[1][1] + X[2][2]*Y[2][1]) % m,
            (X[2][0]*Y[0][2] + X[2][1]*Y[1][2] + X[2][2]*Y[2][2]) % m
        ]
    ]
    return Z
    
    

def power(X,n,m):
    Y = [[1,0,0],[0,1,0],[0,0,1]]
    while(n>0):
        if(n%2 == 1):
            Y = mul(Y,X,m)
        X = mul(X,X,m)
        n = n//2
    return Y
def fib(n,m):
    A = [[2,0,-3],[1,0,0],[0,1,0]]
    An = power(A,n-2,m)
    fn = [2,1,0]
    ans = []
    for i in range(0,3):
        sumi = 0
        for j in range(3):
            sumi = (sumi+An[i][j]*fn[j])%m
        ans.append(sumi)
    return ans[0]
            
print(fib(10,100))