# Design an efficient algorithm to compute \(F(n)\).
def fib_linear(n,m):
    a = 0
    b = 1
    c = 2
    for i in range(3,n+1):
        t = (a+b+c+1)%m
        a = b
        b = c 
        c = t
    return t

